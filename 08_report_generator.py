"""Sales report generator — builds and saves region summaries."""

from __future__ import annotations

import csv
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Tuple


def load_sales(path: str | Path) -> List[Dict[str, str]]:
    """Load sales records from a CSV file with robust error handling."""
    filepath = Path(path)
    if not filepath.is_file():
        raise FileNotFoundError(f"Sales data file not found: {filepath}")

    rows: List[Dict[str, str]] = []
    try:
        with filepath.open(newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if row:
                    rows.append(row)
    except Exception as e:
        raise RuntimeError(f"Failed to parse CSV file '{filepath}': {e}") from e

    return rows


def summarize(rows: List[Dict[str, str]]) -> Dict[str, float]:
    """Summarize total sales amounts per region."""
    totals: Dict[str, float] = {}
    for row in rows:
        region_raw = row.get("region")
        amount_raw = row.get("amount")
        
        if not region_raw:
            continue
            
        region = region_raw.strip()
        try:
            amount = float(amount_raw) if amount_raw else 0.0
        except (ValueError, TypeError):
            amount = 0.0
            
        totals[region] = totals.get(region, 0.0) + amount
        
    return totals


def top_region(totals: Dict[str, float]) -> str | None:
    """Return the region with the highest sales."""
    if not totals:
        return None
    
    best_region, _ = max(totals.items(), key=lambda item: item[1])
    return best_region


def format_report(totals: Dict[str, float], generated_by: str = "system") -> str:
    """Format sales summary totals into a clean text report."""
    lines = ["SALES REPORT", "============"]
    for region in sorted(totals):
        lines.append(f"{region:>12}: {totals[region]:.2f}")
    lines.append(f"Generated by {generated_by} on {datetime.now():%Y-%m-%d}")
    return "\n".join(lines)


def save_report(report: str, path: str | Path = "report.txt") -> None:
    """Save the generated report string to a specified file path."""
    filepath = Path(path)
    try:
        with filepath.open("w", encoding="utf-8") as f:
            f.write(report + "\n")
    except Exception as e:
        raise RuntimeError(f"Failed to save report to '{filepath}': {e}") from e


